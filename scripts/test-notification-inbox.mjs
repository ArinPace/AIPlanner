import {chromium} from 'playwright-core'
import fs from 'node:fs'
import assert from 'node:assert/strict'
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
try{
 const page=await browser.newPage({viewport:{width:393,height:852},isMobile:true,hasTouch:true})
 await page.addInitScript({content:`globalThis.__plannerFixtureSignedIn=true;${fs.readFileSync(new URL('../ios/AIPlanner/UITestFixture.js',import.meta.url),'utf8')}`})
 await page.goto('http://127.0.0.1:5174')
 await page.getByRole('button',{name:'Agent',exact:true}).click()
 const main=page.locator('.agent-tab-panel').filter({visible:true})
 const show=main.getByRole('button',{name:'Show chat sidebar'})
 if(await show.count())await show.click()
 await main.getByRole('button',{name:'Notifications (1)',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Notifications',exact:true})
 await dialog.getByText('Reconnect this source.',{exact:true}).waitFor()
 await dialog.getByRole('checkbox').click()
 await page.waitForFunction(()=>document.querySelector('[aria-label="Notifications"] input')?.checked===true)
 await page.waitForTimeout(200)
 await dialog.getByRole('button',{name:'Close notifications'}).click()
 await page.reload()
 await page.getByRole('button',{name:'Agent',exact:true}).click()
 if(await show.count())await show.click()
 await main.getByRole('button',{name:'Notifications',exact:true}).click()
 assert(await dialog.getByRole('checkbox').isChecked())
 await dialog.getByText('Still needs attention',{exact:false}).waitFor()
 await dialog.getByRole('button',{name:'Close notifications'}).click()
 await page.getByRole('button',{name:'Calendar',exact:true}).click()
 const calendarSidebar=page.locator('aside.sidebar')
 if(!(await calendarSidebar.getAttribute('class')).includes('is-open'))await page.getByRole('button',{name:/Toggle sidebar/}).click()
 await calendarSidebar.getByRole('button',{name:'Manage Google calendars'}).click()
 await calendarSidebar.getByText('arin@example.com',{exact:false}).waitFor()
 await calendarSidebar.getByRole('button',{name:'Add read-only calendar'}).waitFor()
 assert.equal(await calendarSidebar.getByRole('button',{name:'Connect email + calendar'}).count(),0)
 console.log('Mobile notification checklist/reload and Calendar account management passed')
}finally{await browser.close()}
